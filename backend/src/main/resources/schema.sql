DROP TABLE IF EXISTS evento_partido;
DROP TABLE IF EXISTS partido;
DROP TABLE IF EXISTS jugador;
DROP TABLE IF EXISTS equipo;
DROP TABLE IF EXISTS cancha;
DROP TABLE IF EXISTS arbitro;
DROP TABLE IF EXISTS torneo;
DROP TABLE IF EXISTS usuario;

CREATE TABLE usuario (
                         id               INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         username         VARCHAR(40)  NOT NULL UNIQUE,
                         password_hash    VARCHAR(60)  NOT NULL,
                         nombre_completo  VARCHAR(100) NOT NULL,
                         rol              VARCHAR(20)  NOT NULL CHECK (rol IN ('ADMIN', 'DELEGADO')),
                         activo           BOOLEAN      NOT NULL DEFAULT TRUE,
                         fecha_alta       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE torneo (
                        id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        nombre  VARCHAR(80) NOT NULL,
                        anio    INT         NOT NULL,
                        activo  BOOLEAN     NOT NULL DEFAULT TRUE
);

CREATE TABLE equipo (
                        id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        torneo_id  INT         NOT NULL REFERENCES torneo(id),
                        nombre     VARCHAR(80) NOT NULL,
                        barrio     VARCHAR(80),
                        activo     BOOLEAN     NOT NULL DEFAULT TRUE,
                        CONSTRAINT uq_equipo_nombre_torneo UNIQUE (torneo_id, nombre)
);

CREATE TABLE jugador (
                         id               INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         equipo_id        INT         NOT NULL REFERENCES equipo(id),
                         nombre           VARCHAR(60) NOT NULL,
                         apellido         VARCHAR(60) NOT NULL,
                         dni              VARCHAR(10) NOT NULL UNIQUE,
                         numero_camiseta  INT         CHECK (numero_camiseta BETWEEN 1 AND 99),
                         activo           BOOLEAN     NOT NULL DEFAULT TRUE
);

CREATE TABLE cancha (
                        id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        nombre     VARCHAR(60)  NOT NULL UNIQUE,
                        direccion  VARCHAR(120),
                        activo     BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE arbitro (
                         id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         nombre    VARCHAR(60) NOT NULL,
                         apellido  VARCHAR(60) NOT NULL,
                         dni       VARCHAR(10) NOT NULL UNIQUE,
                         activo    BOOLEAN     NOT NULL DEFAULT TRUE
);

CREATE TABLE partido (
                         id                   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         torneo_id            INT         NOT NULL REFERENCES torneo(id),
                         numero_fecha         INT         NOT NULL CHECK (numero_fecha >= 1),
                         equipo_local_id      INT         NOT NULL REFERENCES equipo(id),
                         equipo_visitante_id  INT         NOT NULL REFERENCES equipo(id),
                         cancha_id            INT         NOT NULL REFERENCES cancha(id),
                         arbitro_id           INT         NOT NULL REFERENCES arbitro(id),
                         fecha_hora_inicio    TIMESTAMP   NOT NULL,
                         estado               VARCHAR(20) NOT NULL DEFAULT 'PROGRAMADO'
                             CHECK (estado IN ('PROGRAMADO', 'EN_JUEGO', 'FINALIZADO', 'SUSPENDIDO')),
                         CONSTRAINT ck_partido_equipos CHECK (equipo_local_id <> equipo_visitante_id)
);

CREATE TABLE evento_partido (
                                id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                partido_id  INT         NOT NULL REFERENCES partido(id),
                                jugador_id  INT         NOT NULL REFERENCES jugador(id),
                                tipo        VARCHAR(20) NOT NULL CHECK (tipo IN ('GOL', 'AMARILLA', 'ROJA')),
                                minuto      INT         NOT NULL CHECK (minuto BETWEEN 1 AND 120)
);